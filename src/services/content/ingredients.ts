export function findIngredientById(id: string): Ingredient | undefined {
  return INGREDIENTS_DATABASE.find((item) => item.id === id);
}

export function findIngredientByName(query: string): Ingredient | undefined {
  const needle = query.trim().toLowerCase();
  if (!needle) return undefined;
  return INGREDIENTS_DATABASE.find(
    (item) => item.id === needle || item.name.toLowerCase() === needle || item.nameFa === query.trim(),
  );
}

/** همهٔ ترکیبات یک دسته (مانند همهٔ رتینوئیدها یا همهٔ AHAها). */
export function ingredientIdsOfClass(...classes: string[]): string[] {
  return INGREDIENTS_DATABASE.filter((item) => item.activeClass && classes.includes(item.activeClass)).map(
    (item) => item.id,
  );
}
